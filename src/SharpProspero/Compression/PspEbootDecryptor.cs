using SharpProspero.Security;
using System;
using System.Buffers.Binary;

namespace SharpProspero.Compression;

/// <summary>
/// Decrypts a PSP EBOOT.BIN wrapped in the ~PSP container. Reads the 32-bit tag identifier at offset
/// 0xD0, walks five different container flavours (types 0, 1, 2, 5 and 6) in turn, and returns the
/// plaintext PRX produced by the KIRK command 1 body-decrypt pipeline.
/// </summary>
/// <remarks>
/// <para>
/// Each flavour rebuilds a KIRK command 1 header from a different slice of the container, verifies the
/// SHA-1 checksum stored in the header, seeds a KIRK 7 pass to unwrap the sub-key seed, then feeds
/// the reconstructed header and the encrypted body through
/// <see cref="KirkEngine.sceUtilsBufferCopyWithRange(byte[], int, byte[], int, int)"/>. Types 2, 5 and
/// 6 use the 16-byte sub-key table published in <see cref="PspPrxTags"/>; types 0 and 1 use a
/// separate table of 144-byte pre-expanded seeds carried in this class.
/// </para>
/// <para>
/// Callers that only need to classify a buffer or check whether a tag has a bundled key reach for
/// <see cref="IsPspEboot"/>, <see cref="TryPeekTag"/> and <see cref="HasKeyForTag"/>. <see cref="Decrypt"/>
/// throws on failure while <see cref="TryDecrypt"/> reports the outcome as a bool.
/// </para>
/// </remarks>
public static class PspEbootDecryptor
{
    /// <summary>Total size of the ~PSP container header in bytes; the encrypted body starts here.</summary>
    private const int HeaderSize = 0x150;

    /// <summary>Byte offset of the 32-bit little-endian tag identifier within the ~PSP header.</summary>
    private const int TagOffset = 0xD0;

    /// <summary>Byte offset of the plaintext s32 that carries the decrypted PRX size.</summary>
    private const int DecryptSizeOffset = 0xB0;

    /// <summary>Size of a KIRK command 1 header (both the plain and ECDSA-augmented shapes).</summary>
    private const int KirkCmd1HeaderSize = 0x90;

    /// <summary>Size of the prxHeader region that sits between the KIRK header and the encrypted body.</summary>
    private const int PrxHeaderSize = 0x80;

    // The KIRK header sits at (PSP header size - its own 0x90 - the 0x80 prxHeader that follows),
    // so the encrypted body at file offset 0x150 lines up with data_offset = 0x80 inside the KIRK
    // command 1 layout.
    private const int KirkInputOffset = HeaderSize - KirkCmd1HeaderSize - PrxHeaderSize;

    /// <summary>
    /// The four-byte container magic that marks an encrypted PSP EBOOT: 0x7E 0x50 0x53 0x50
    /// (the ASCII bytes for "~PSP").
    /// </summary>
    private static ReadOnlySpan<byte> HeaderMagic => [0x7E, 0x50, 0x53, 0x50];

    /// <summary>
    /// Fixed 16-byte AES-128 key that a KIRK command 1 body-decrypt pass consumes once the wrapped
    /// header keys have been unwrapped. Kept exposed for consumers that still reference it.
    /// </summary>
    internal static ReadOnlySpan<byte> KirkAesKey =>
    [
        0x98, 0xC9, 0x40, 0x97, 0x5C, 0x1D, 0x10, 0xE8,
        0x7F, 0xE6, 0x0E, 0xA3, 0xFD, 0x03, 0xA8, 0xBA,
    ];

    /// <summary>
    /// Reports whether a buffer carries the ~PSP EBOOT container magic and is large enough
    /// to hold the full header. Does not touch the tag or the encrypted body.
    /// </summary>
    /// <param name="encryptedEboot">The buffer to inspect.</param>
    /// <returns>
    /// <c>true</c> when the buffer is at least the ~PSP header size and starts with the
    /// four-byte ~PSP magic; <c>false</c> otherwise.
    /// </returns>
    public static bool IsPspEboot(ReadOnlySpan<byte> encryptedEboot)
    {
        return encryptedEboot.Length >= HeaderSize
            && encryptedEboot[..4].SequenceEqual(HeaderMagic);
    }

    /// <summary>
    /// Reads the 32-bit tag identifier from a ~PSP-wrapped buffer without attempting any
    /// decryption. Useful for classifying which sub-key a payload would need.
    /// </summary>
    /// <param name="encryptedEboot">The raw ~PSP-wrapped EBOOT.BIN buffer.</param>
    /// <param name="tag">
    /// Receives the 32-bit little-endian tag at offset 0xD0 on success; 0 otherwise.
    /// </param>
    /// <returns>
    /// <c>true</c> when the buffer is at least the ~PSP header size and carries the ~PSP
    /// magic at offset 0; <c>false</c> otherwise.
    /// </returns>
    public static bool TryPeekTag(ReadOnlySpan<byte> encryptedEboot, out uint tag)
    {
        tag = 0;

        if (encryptedEboot.Length < HeaderSize)
            return false;

        if (!encryptedEboot[..4].SequenceEqual(HeaderMagic))
            return false;

        tag = BinaryPrimitives.ReadUInt32LittleEndian(encryptedEboot.Slice(TagOffset, 4));
        return true;
    }

    /// <summary>
    /// Reports whether the bundled sub-key tables carry an entry for the given tag. Consults both
    /// the 144-byte pre-expanded seed table (types 0 and 1) and the 16-byte sub-key table published
    /// in <see cref="PspPrxTags"/> (types 2, 5 and 6).
    /// </summary>
    /// <param name="tag">The 32-bit little-endian tag identifier from the ~PSP header.</param>
    /// <returns><c>true</c> when either table carries an entry for the tag; <c>false</c> otherwise.</returns>
    public static bool HasKeyForTag(uint tag)
        => GetTagInfoV1(tag) != null || PspPrxTags.GetTagInfo(tag) != null;

    /// <summary>
    /// Decrypts a ~PSP-wrapped EBOOT.BIN and returns the plaintext PRX. Tries each container
    /// flavour in turn (types 0, 1, 2, 5 and 6) and returns the first result whose SHA-1 checksum
    /// matches and whose KIRK command 1 body-decrypt pass succeeds.
    /// </summary>
    /// <param name="encryptedEboot">The raw ~PSP-wrapped EBOOT.BIN buffer.</param>
    /// <returns>The decrypted PRX bytes.</returns>
    /// <exception cref="ArgumentException">
    /// The buffer is shorter than the 0x150-byte ~PSP header.
    /// </exception>
    /// <exception cref="FormatException">
    /// The buffer does not start with the ~PSP magic at offset 0.
    /// </exception>
    /// <exception cref="NotSupportedException">
    /// No type flavour produced a valid decrypt for the tag at offset 0xD0.
    /// </exception>
    public static byte[] Decrypt(ReadOnlySpan<byte> encryptedEboot)
    {
        if (encryptedEboot.Length < HeaderSize)
            throw new ArgumentException(
                $"Buffer is {encryptedEboot.Length} bytes; ~PSP header requires at least {HeaderSize}.",
                nameof(encryptedEboot));

        if (!encryptedEboot[..4].SequenceEqual(HeaderMagic))
            throw new FormatException(
                "Buffer is not a ~PSP EBOOT container (magic mismatch at offset 0).");

        if (TryDecrypt(encryptedEboot, out byte[] plain))
            return plain;

        uint tag = BinaryPrimitives.ReadUInt32LittleEndian(encryptedEboot.Slice(TagOffset, 4));
        throw new NotSupportedException(
            $"~PSP EBOOT tag 0x{tag:X8} could not be decrypted by any type dispatch.");
    }

    /// <summary>
    /// Attempts to decrypt a ~PSP-wrapped EBOOT.BIN and reports the outcome as a bool. Callers rely
    /// on this method to gate a re-embed pass so a failing decrypt leaves the input buffer untouched.
    /// </summary>
    /// <param name="encryptedEboot">The raw ~PSP-wrapped EBOOT.BIN buffer.</param>
    /// <param name="decrypted">
    /// Receives the decrypted PRX bytes on success; an empty array on failure.
    /// </param>
    /// <returns>
    /// <c>true</c> when a type dispatch produced a valid decrypt; <c>false</c> when every attempt
    /// failed (bad magic, short buffer, unknown tag, SHA-1 mismatch or KIRK dispatch error).
    /// </returns>
    public static bool TryDecrypt(ReadOnlySpan<byte> encryptedEboot, out byte[] decrypted)
    {
        decrypted = [];

        if (encryptedEboot.Length < HeaderSize)
            return false;

        if (!encryptedEboot[..4].SequenceEqual(HeaderMagic))
            return false;

        byte[] inbuf = encryptedEboot.ToArray();
        int size = inbuf.Length;
        byte[] outbuf = new byte[size];

        int res = PspDecryptType0(inbuf, outbuf, size);
        if (res >= 0) { decrypted = ExtractPlaintext(outbuf, res); return true; }

        res = PspDecryptType1(inbuf, outbuf, size);
        if (res >= 0) { decrypted = ExtractPlaintext(outbuf, res); return true; }

        res = PspDecryptType2(inbuf, outbuf, size);
        if (res >= 0) { decrypted = ExtractPlaintext(outbuf, res); return true; }

        res = PspDecryptType5(inbuf, outbuf, size, null);
        if (res >= 0) { decrypted = ExtractPlaintext(outbuf, res); return true; }

        res = PspDecryptType6(inbuf, outbuf, size);
        if (res >= 0) { decrypted = ExtractPlaintext(outbuf, res); return true; }

        return false;
    }

    private static byte[] ExtractPlaintext(byte[] outbuf, int size)
    {
        byte[] result = new byte[size];
        Buffer.BlockCopy(outbuf, 0, result, 0, size);
        return result;
    }

    // ------------------------- Type dispatchers -------------------------

    private static int PspDecryptType0(byte[] inbuf, byte[] outbuf, int size)
    {
        int decryptSize = BinaryPrimitives.ReadInt32LittleEndian(inbuf.AsSpan(DecryptSizeOffset, 4));
        uint tag = BinaryPrimitives.ReadUInt32LittleEndian(inbuf.AsSpan(TagOffset, 4));
        PrxTagInfo1? ptiOpt = GetTagInfoV1(tag);
        if (ptiOpt == null) return -1;
        PrxTagInfo1 pti = ptiOpt.Value;

        // The 144-byte v1 key is the KIRK 7 pre-decrypted seed, used as the xorbuf directly.
        byte[] xorbuf = new byte[0x90];
        Buffer.BlockCopy(pti.Key, 0, xorbuf, 0, 0x90);

        // Type 0 layout: kirkBlock is prx[0x110..0x150] followed by prx[0x80..0xD0].
        byte[] sha1Stored = new byte[0x14];
        byte[] unused = new byte[0x28];
        byte[] kirkBlock = new byte[0x90];
        byte[] prxHeader = new byte[PrxHeaderSize];
        Buffer.BlockCopy(inbuf, 0xD4, sha1Stored, 0, 0x14);
        Buffer.BlockCopy(inbuf, 0xE8, unused, 0, 0x28);
        Buffer.BlockCopy(inbuf, 0x110, kirkBlock, 0, 0x40);
        Buffer.BlockCopy(inbuf, 0x80, kirkBlock, 0x40, 0x50);
        Buffer.BlockCopy(inbuf, 0, prxHeader, 0, PrxHeaderSize);

        var sha = new Sha1();
        sha.Update(xorbuf.AsSpan(0, 0x14));
        sha.Update(unused);
        sha.Update(kirkBlock);
        sha.Update(prxHeader);
        Span<byte> computed = stackalloc byte[0x14];
        sha.Finish(computed);
        if (!computed.SequenceEqual(sha1Stored)) return -3;

        byte[] kirkInput = new byte[size - KirkInputOffset];
        Buffer.BlockCopy(kirkBlock, 0, kirkInput, 0, 0x90);
        Buffer.BlockCopy(prxHeader, 0, kirkInput, 0x90, PrxHeaderSize);
        Buffer.BlockCopy(inbuf, HeaderSize, kirkInput, 0x110, size - HeaderSize);
        DecryptKirkHeaderType0(kirkInput.AsSpan(0, 0x70), kirkBlock, xorbuf, pti.Code);

        int retv = KirkEngine.sceUtilsBufferCopyWithRange(
            outbuf, size, kirkInput, kirkInput.Length, KirkState.KIRK_CMD_DECRYPT_PRIVATE);
        if (retv != 0) return -4;
        return decryptSize;
    }

    private static int PspDecryptType1(byte[] inbuf, byte[] outbuf, int size)
    {
        int decryptSize = BinaryPrimitives.ReadInt32LittleEndian(inbuf.AsSpan(DecryptSizeOffset, 4));
        uint tag = BinaryPrimitives.ReadUInt32LittleEndian(inbuf.AsSpan(TagOffset, 4));
        PrxTagInfo1? ptiOpt = GetTagInfoV1(tag);
        if (ptiOpt == null) return -1;
        PrxTagInfo1 pti = ptiOpt.Value;

        byte[] xorbuf = new byte[0x90];
        Buffer.BlockCopy(pti.Key, 0, xorbuf, 0, 0x90);

        byte[] sha1Stored = new byte[0x14];
        byte[] unused = new byte[0x28];
        byte[] kirkBlock = new byte[0x90];
        byte[] prxHeader = new byte[PrxHeaderSize];
        Buffer.BlockCopy(inbuf, 0xD4, sha1Stored, 0, 0x14);
        Buffer.BlockCopy(inbuf, 0xE8, unused, 0, 0x28);
        Buffer.BlockCopy(inbuf, 0x110, kirkBlock, 0, 0x40);
        Buffer.BlockCopy(inbuf, 0x80, kirkBlock, 0x40, 0x50);
        Buffer.BlockCopy(inbuf, 0, prxHeader, 0, PrxHeaderSize);

        // Type 1 KIRK 7 pre-pass covers 0xA0 bytes starting at sha1[0xC], which under the packed
        // struct layout runs across sha1[0xC..0x14] + unused[0..0x28] + kirkBlock[0..0x70]; assemble
        // the region in a scratch buffer, decrypt it, then copy each slice back.
        byte[] joined = new byte[0xA0];
        Buffer.BlockCopy(sha1Stored, 0x0C, joined, 0, 0x08);
        Buffer.BlockCopy(unused, 0, joined, 0x08, 0x28);
        Buffer.BlockCopy(kirkBlock, 0, joined, 0x30, 0x70);
        KirkState.Kirk7(joined, joined, 0xA0, pti.Code);
        Buffer.BlockCopy(joined, 0, sha1Stored, 0x0C, 0x08);
        Buffer.BlockCopy(joined, 0x08, unused, 0, 0x28);
        Buffer.BlockCopy(joined, 0x30, kirkBlock, 0, 0x70);

        var sha = new Sha1();
        sha.Update(xorbuf.AsSpan(0, 0x14));
        sha.Update(unused);
        sha.Update(kirkBlock);
        sha.Update(prxHeader);
        Span<byte> computed = stackalloc byte[0x14];
        sha.Finish(computed);
        if (!computed.SequenceEqual(sha1Stored)) return -3;

        byte[] kirkInput = new byte[size - KirkInputOffset];
        Buffer.BlockCopy(kirkBlock, 0, kirkInput, 0, 0x90);
        Buffer.BlockCopy(prxHeader, 0, kirkInput, 0x90, PrxHeaderSize);
        Buffer.BlockCopy(inbuf, HeaderSize, kirkInput, 0x110, size - HeaderSize);
        DecryptKirkHeaderType0(kirkInput.AsSpan(0, 0x70), kirkBlock, xorbuf, pti.Code);

        int retv = KirkEngine.sceUtilsBufferCopyWithRange(
            outbuf, size, kirkInput, kirkInput.Length, KirkState.KIRK_CMD_DECRYPT_PRIVATE);
        if (retv != 0) return -4;
        return decryptSize;
    }

    private static int PspDecryptType2(byte[] inbuf, byte[] outbuf, int size)
    {
        int decryptSize = BinaryPrimitives.ReadInt32LittleEndian(inbuf.AsSpan(DecryptSizeOffset, 4));
        uint tag = BinaryPrimitives.ReadUInt32LittleEndian(inbuf.AsSpan(TagOffset, 4));
        PspPrxTags.PrxTagInfo? ptiOpt = PspPrxTags.GetTagInfo(tag);
        if (ptiOpt == null) return -1;
        PspPrxTags.PrxTagInfo pti = ptiOpt.Value;

        byte[] xorbuf = ExpandSeed(pti.Key, pti.Code);

        byte[] tagBytes = new byte[4];
        byte[] empty = new byte[0x58];
        byte[] id = new byte[0x10];
        byte[] sha1Stored = new byte[0x14];
        byte[] kirkHeader = new byte[0x40];
        byte[] kirkMetadata = new byte[0x10];
        byte[] prxHeader = new byte[PrxHeaderSize];
        Buffer.BlockCopy(inbuf, 0xD0, tagBytes, 0, 4);
        Buffer.BlockCopy(inbuf, 0x140, id, 0, 0x10);
        Buffer.BlockCopy(inbuf, 0x12C, sha1Stored, 0, 0x14);
        Buffer.BlockCopy(inbuf, 0x80, kirkHeader, 0, 0x30);
        Buffer.BlockCopy(inbuf, 0xC0, kirkHeader, 0x30, 0x10);
        Buffer.BlockCopy(inbuf, 0xB0, kirkMetadata, 0, 0x10);
        Buffer.BlockCopy(inbuf, 0, prxHeader, 0, PrxHeaderSize);

        // Type 2 KIRK 7 pre-pass covers 0x60 bytes at &id, which under the packed struct layout runs
        // across id[0..0x10] + sha1[0..0x14] + kirkHeader[0..0x3C]; join the region, decrypt in
        // place, then copy each slice back to its own buffer.
        byte[] joined = new byte[0x60];
        Buffer.BlockCopy(id, 0, joined, 0, 0x10);
        Buffer.BlockCopy(sha1Stored, 0, joined, 0x10, 0x14);
        Buffer.BlockCopy(kirkHeader, 0, joined, 0x24, 0x3C);
        KirkState.Kirk7(joined, joined, 0x60, pti.Code);
        Buffer.BlockCopy(joined, 0, id, 0, 0x10);
        Buffer.BlockCopy(joined, 0x10, sha1Stored, 0, 0x14);
        Buffer.BlockCopy(joined, 0x24, kirkHeader, 0, 0x3C);

        var sha = new Sha1();
        sha.Update(tagBytes);
        sha.Update(xorbuf.AsSpan(0, 0x10));
        sha.Update(empty);
        sha.Update(id);
        sha.Update(kirkHeader);
        sha.Update(kirkMetadata);
        sha.Update(prxHeader);
        Span<byte> computed = stackalloc byte[0x14];
        sha.Finish(computed);
        if (!computed.SequenceEqual(sha1Stored)) return -3;

        byte[] kirkInput = new byte[size - KirkInputOffset];
        // The KIRK header is a zeroed 0x90 region with data_size / data_offset / unk4 filled from
        // kirkMetadata and mode set to 1; the decryptKirkHeader pass then unwraps the 0x40-byte
        // key + hash block at the head.
        Buffer.BlockCopy(kirkMetadata, 0, kirkInput, 0x70, 0x10);
        Buffer.BlockCopy(prxHeader, 0, kirkInput, 0x90, PrxHeaderSize);
        Buffer.BlockCopy(inbuf, HeaderSize, kirkInput, 0x110, size - HeaderSize);
        DecryptKirkHeader(kirkInput.AsSpan(0, 0x40), kirkHeader, xorbuf.AsSpan(0x10), pti.Code);
        BinaryPrimitives.WriteUInt32LittleEndian(kirkInput.AsSpan(0x60, 4), 1u);

        int retv = KirkEngine.sceUtilsBufferCopyWithRange(
            outbuf, size, kirkInput, kirkInput.Length, KirkState.KIRK_CMD_DECRYPT_PRIVATE);
        if (retv != 0) return -4;
        return decryptSize;
    }

    private static int PspDecryptType5(byte[] inbuf, byte[] outbuf, int size, byte[]? externalSeed)
    {
        int decryptSize = BinaryPrimitives.ReadInt32LittleEndian(inbuf.AsSpan(DecryptSizeOffset, 4));
        uint tag = BinaryPrimitives.ReadUInt32LittleEndian(inbuf.AsSpan(TagOffset, 4));
        PspPrxTags.PrxTagInfo? ptiOpt = PspPrxTags.GetTagInfo(tag);
        if (ptiOpt == null) return -1;
        PspPrxTags.PrxTagInfo pti = ptiOpt.Value;
        byte[]? xor1 = GetType5Xor(tag);

        byte[] xorbuf = ExpandSeed(pti.Key, pti.Code, externalSeed);

        byte[] tagBytes = new byte[4];
        byte[] empty = new byte[0x58];
        byte[] id = new byte[0x10];
        byte[] sha1Stored = new byte[0x14];
        byte[] kirkHeader = new byte[0x40];
        byte[] kirkMetadata = new byte[0x10];
        byte[] prxHeader = new byte[PrxHeaderSize];
        Buffer.BlockCopy(inbuf, 0xD0, tagBytes, 0, 4);
        Buffer.BlockCopy(inbuf, 0x140, id, 0, 0x10);
        Buffer.BlockCopy(inbuf, 0x12C, sha1Stored, 0, 0x14);
        Buffer.BlockCopy(inbuf, 0x80, kirkHeader, 0, 0x30);
        Buffer.BlockCopy(inbuf, 0xC0, kirkHeader, 0x30, 0x10);
        Buffer.BlockCopy(inbuf, 0xB0, kirkMetadata, 0, 0x10);
        Buffer.BlockCopy(inbuf, 0, prxHeader, 0, PrxHeaderSize);

        // Type 5 in-place transform: kirkHeader (0x40) plus first 0x10 of sha1Stored are joined,
        // XORed with the tag's xor1 and the external seed (both optional), KIRK 7 decrypted, then
        // written back; then id (0x60) is XORed with xor1 and KIRK 7 decrypted.
        Span<byte> data = stackalloc byte[0x50];
        kirkHeader.CopyTo(data);
        sha1Stored.AsSpan(0, 0x10).CopyTo(data[0x40..]);
        for (int i = 0; i < 0x50; i++)
        {
            if (xor1 != null) data[i] ^= xor1[i % 0x10];
            if (externalSeed != null) data[i] ^= externalSeed[i % 0x10];
        }
        KirkState.Kirk7(data, data, 0x50, pti.Code);
        data[..0x40].CopyTo(kirkHeader);
        data.Slice(0x40, 0x10).CopyTo(sha1Stored.AsSpan(0, 0x10));

        // The XOR + KIRK 7 pass on &id runs across 0x60 bytes = id[0..0x10] + sha1[0..0x14] +
        // kirkHeader[0..0x3C] under the packed struct layout; assemble the region, apply xor1 and
        // KIRK 7 in place, then copy each slice back to its own buffer.
        byte[] joined = new byte[0x60];
        Buffer.BlockCopy(id, 0, joined, 0, 0x10);
        Buffer.BlockCopy(sha1Stored, 0, joined, 0x10, 0x14);
        Buffer.BlockCopy(kirkHeader, 0, joined, 0x24, 0x3C);
        if (xor1 != null)
        {
            for (int i = 0; i < 0x60; i++) joined[i] ^= xor1[i % 0x10];
        }
        KirkState.Kirk7(joined, joined, 0x60, pti.Code);
        Buffer.BlockCopy(joined, 0, id, 0, 0x10);
        Buffer.BlockCopy(joined, 0x10, sha1Stored, 0, 0x14);
        Buffer.BlockCopy(joined, 0x24, kirkHeader, 0, 0x3C);

        var sha = new Sha1();
        sha.Update(tagBytes);
        sha.Update(xorbuf.AsSpan(0, 0x10));
        sha.Update(empty);
        sha.Update(id);
        sha.Update(kirkHeader);
        sha.Update(kirkMetadata);
        sha.Update(prxHeader);
        Span<byte> computed = stackalloc byte[0x14];
        sha.Finish(computed);
        if (!computed.SequenceEqual(sha1Stored)) return -3;

        byte[] kirkInput = new byte[size - KirkInputOffset];
        Buffer.BlockCopy(kirkMetadata, 0, kirkInput, 0x70, 0x10);
        Buffer.BlockCopy(prxHeader, 0, kirkInput, 0x90, PrxHeaderSize);
        Buffer.BlockCopy(inbuf, HeaderSize, kirkInput, 0x110, size - HeaderSize);
        DecryptKirkHeader(kirkInput.AsSpan(0, 0x40), kirkHeader, xorbuf.AsSpan(0x10), pti.Code);
        BinaryPrimitives.WriteUInt32LittleEndian(kirkInput.AsSpan(0x60, 4), 1u);

        int retv = KirkEngine.sceUtilsBufferCopyWithRange(
            outbuf, size, kirkInput, kirkInput.Length, KirkState.KIRK_CMD_DECRYPT_PRIVATE);
        if (retv != 0) return -4;
        return decryptSize;
    }

    private static int PspDecryptType6(byte[] inbuf, byte[] outbuf, int size)
    {
        int decryptSize = BinaryPrimitives.ReadInt32LittleEndian(inbuf.AsSpan(DecryptSizeOffset, 4));
        uint tag = BinaryPrimitives.ReadUInt32LittleEndian(inbuf.AsSpan(TagOffset, 4));
        PspPrxTags.PrxTagInfo? ptiOpt = PspPrxTags.GetTagInfo(tag);
        if (ptiOpt == null) return -1;
        PspPrxTags.PrxTagInfo pti = ptiOpt.Value;

        byte[] xorbuf = ExpandSeed(pti.Key, pti.Code);

        byte[] tagBytes = new byte[4];
        byte[] empty = new byte[0x38];
        byte[] ecdsaSignatureTail = new byte[0x20];
        byte[] id = new byte[0x10];
        byte[] sha1Stored = new byte[0x14];
        byte[] kirkHeader = new byte[0x40];
        byte[] kirkMetadata = new byte[0x10];
        byte[] prxHeader = new byte[PrxHeaderSize];
        Buffer.BlockCopy(inbuf, 0xD0, tagBytes, 0, 4);
        Buffer.BlockCopy(inbuf, 0x10C, ecdsaSignatureTail, 0, 0x20);
        Buffer.BlockCopy(inbuf, 0x140, id, 0, 0x10);
        Buffer.BlockCopy(inbuf, 0x12C, sha1Stored, 0, 0x14);
        Buffer.BlockCopy(inbuf, 0x80, kirkHeader, 0, 0x30);
        Buffer.BlockCopy(inbuf, 0xC0, kirkHeader, 0x30, 0x10);
        Buffer.BlockCopy(inbuf, 0xB0, kirkMetadata, 0, 0x10);
        Buffer.BlockCopy(inbuf, 0, prxHeader, 0, PrxHeaderSize);

        // Type 6 KIRK 7 pre-pass covers 0x60 bytes at &id, which under the packed struct layout runs
        // across id[0..0x10] + sha1[0..0x14] + kirkHeader[0..0x3C]; join the region, decrypt in
        // place, then copy each slice back to its own buffer.
        byte[] joined = new byte[0x60];
        Buffer.BlockCopy(id, 0, joined, 0, 0x10);
        Buffer.BlockCopy(sha1Stored, 0, joined, 0x10, 0x14);
        Buffer.BlockCopy(kirkHeader, 0, joined, 0x24, 0x3C);
        KirkState.Kirk7(joined, joined, 0x60, pti.Code);
        Buffer.BlockCopy(joined, 0, id, 0, 0x10);
        Buffer.BlockCopy(joined, 0x10, sha1Stored, 0, 0x14);
        Buffer.BlockCopy(joined, 0x24, kirkHeader, 0, 0x3C);

        var sha = new Sha1();
        sha.Update(tagBytes);
        sha.Update(xorbuf.AsSpan(0, 0x10));
        sha.Update(empty);
        sha.Update(ecdsaSignatureTail);
        sha.Update(id);
        sha.Update(kirkHeader);
        sha.Update(kirkMetadata);
        sha.Update(prxHeader);
        Span<byte> computed = stackalloc byte[0x14];
        sha.Finish(computed);
        if (!computed.SequenceEqual(sha1Stored)) return -3;

        byte[] kirkInput = new byte[size - KirkInputOffset];
        // The ECDSA header shape carries the signature tail at 0x40..0x60, kirkMetadata at
        // 0x70..0x80, mode = 1 at 0x60 and ecdsa_hash = 1 at 0x64.
        Buffer.BlockCopy(ecdsaSignatureTail, 0, kirkInput, 0x40, 0x20);
        Buffer.BlockCopy(kirkMetadata, 0, kirkInput, 0x70, 0x10);
        Buffer.BlockCopy(prxHeader, 0, kirkInput, 0x90, PrxHeaderSize);
        Buffer.BlockCopy(inbuf, HeaderSize, kirkInput, 0x110, size - HeaderSize);
        DecryptKirkHeader(kirkInput.AsSpan(0, 0x40), kirkHeader, xorbuf.AsSpan(0x10), pti.Code);
        BinaryPrimitives.WriteUInt32LittleEndian(kirkInput.AsSpan(0x60, 4), 1u);
        kirkInput[0x64] = 1;

        int retv = KirkEngine.sceUtilsBufferCopyWithRange(
            outbuf, size, kirkInput, kirkInput.Length, KirkState.KIRK_CMD_DECRYPT_PRIVATE);
        if (retv != 0) return -4;
        return decryptSize;
    }

    // ------------------------- Helpers -------------------------

    // Fills a 0x90 buffer by tiling the 16-byte seed with the block index written into the first
    // byte of each 16-byte slice, KIRK 7 decrypts it, then optionally XORs it with an external
    // seed tiled the same way.
    private static byte[] ExpandSeed(byte[] seed, byte key, byte[]? bonusSeed = null)
    {
        byte[] expandedSeed = new byte[0x90];
        for (int i = 0; i < expandedSeed.Length; i += 0x10)
        {
            Buffer.BlockCopy(seed, 0, expandedSeed, i, 0x10);
            expandedSeed[i] = (byte)(i / 0x10);
        }
        KirkState.Kirk7(expandedSeed, expandedSeed, expandedSeed.Length, key);
        if (bonusSeed != null)
        {
            for (int i = 0; i < expandedSeed.Length; i++)
                expandedSeed[i] ^= bonusSeed[i % 0x10];
        }
        return expandedSeed;
    }

    // The type 2 / 5 / 6 KIRK header transform: XOR the 0x40 input bytes with xorbuf[0..0x40],
    // KIRK 7 decrypt in place, then XOR the result with xorbuf[0x40..0x80]. Caller passes an
    // already-offset xorbuf slice (typically xorbuf.AsSpan(0x10)).
    private static void DecryptKirkHeader(Span<byte> outbuf, ReadOnlySpan<byte> inbuf, ReadOnlySpan<byte> xorbuf, byte key)
    {
        for (int i = 0; i < 0x40; i++)
            outbuf[i] = (byte)(inbuf[i] ^ xorbuf[i]);
        KirkState.Kirk7(outbuf, outbuf, 0x40, key);
        for (int i = 0; i < 0x40; i++)
            outbuf[i] ^= xorbuf[0x40 + i];
    }

    // The type 0 / 1 KIRK header transform: XOR the 0x70 input bytes with xorbuf[0x14..0x84],
    // KIRK 7 decrypt in place, then XOR the result with xorbuf[0x20..0x90].
    private static void DecryptKirkHeaderType0(Span<byte> outbuf, ReadOnlySpan<byte> inbuf, ReadOnlySpan<byte> xorbuf, byte key)
    {
        for (int i = 0; i < 0x70; i++)
            outbuf[i] = (byte)(inbuf[i] ^ xorbuf[i + 0x14]);
        KirkState.Kirk7(outbuf, outbuf, 0x70, key);
        for (int i = 0; i < 0x70; i++)
            outbuf[i] ^= xorbuf[i + 0x20];
    }

