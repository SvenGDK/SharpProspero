    /// <summary>
    /// Decrypts a 256-byte EEKPFS blob into a 32-byte EKPFS seed using RSA-2048 with
    /// the ypkg key. The EEKPFS is PKCS#1 v1.5 padded: <c>0x00 0x02 [padding] 0x00 [32-byte EKPFS]</c>.
    /// </summary>
    /// <param name="eekpfs">The 256-byte encrypted EKPFS input.</param>
    /// <param name="ekpfs">Receives the 32-byte EKPFS seed on success.</param>
    /// <returns><see langword="true"/> if the RSA operation and PKCS#1 v1.5 unpadding succeeded.</returns>
    public static bool DecryptEekpfs(ReadOnlySpan<byte> eekpfs, Span<byte> ekpfs)
    {
        if (eekpfs.Length != 256 || ekpfs.Length < 32) return false;

        Span<byte> decrypted = stackalloc byte[256];
        Security.Rsa2048.RawOp(eekpfs, YpkgModulus, YpkgExponent, decrypted);

        // Verify PKCS#1 v1.5 type 2 padding: 0x00 0x02 ... 0x00 [32-byte payload]
        if (decrypted[0] != 0x00 || decrypted[1] != 0x02) return false;

        // Find the zero separator after the padding bytes
        int idx = 2;
        while (idx < 256 && decrypted[idx] != 0) idx++;
        if (idx != 255 - 32) return false;

        // Extract the 32-byte EKPFS following the separator
        decrypted[(idx + 1)..].CopyTo(ekpfs);
        return true;
    }

    /// <summary>
    /// Derives the XTS encryption key pair (tweak key + data key, 32 bytes total) and
    /// the HMAC signing key (32 bytes) from an EKPFS seed value and the PFS superblock seed.
    /// The derivation is <c>HMAC-SHA256(ekpfs, LE32(index) || seed[16])</c> where index 1
    /// yields the encryption key and index 2 the signing key.
    /// </summary>
    /// <param name="ekpfs">The 32-byte EKPFS seed.</param>
    /// <param name="seed">The 16-byte PFS superblock crypt seed.</param>
    /// <param name="xtsKey">Receives the 32-byte XTS key (first 16 = tweak key, last 16 = data key).</param>
    /// <param name="hmacKey">Receives the 32-byte HMAC signing key.</param>
    public static void DeriveKeys(ReadOnlySpan<byte> ekpfs, ReadOnlySpan<byte> seed,
        Span<byte> xtsKey, Span<byte> hmacKey)
    {
        Span<byte> hmacData = stackalloc byte[20]; // 4 bytes index + 16 bytes seed
        BinaryPrimitives.WriteUInt32LittleEndian(hmacData, EncKeyIndex);
        seed.Slice(0, 16).CopyTo(hmacData[4..]);

        byte[] encResult = Security.Hmac.Sha256(ekpfs, hmacData);
        encResult.AsSpan(0, Math.Min(encResult.Length, xtsKey.Length)).CopyTo(xtsKey);

        BinaryPrimitives.WriteUInt32LittleEndian(hmacData, SignKeyIndex);
        byte[] sigResult = Security.Hmac.Sha256(ekpfs, hmacData);
        sigResult.AsSpan(0, Math.Min(sigResult.Length, hmacKey.Length)).CopyTo(hmacKey);
    }

    /// <summary>
    /// Decrypts a PFS sector using AES-XTS-128.
    /// </summary>
    /// <param name="data">The sector data to decrypt (modified in place).</param>
    /// <param name="xtsKey">The 32-byte XTS key (first 16 = tweak key, last 16 = data key).</param>
    /// <param name="sectorNumber">The sector number used as the tweak value.</param>
    public static void DecryptSector(Span<byte> data, ReadOnlySpan<byte> xtsKey, ulong sectorNumber)
    {
        var tweakCipher = new Security.Aes128(xtsKey.Slice(0, 16));
        var dataCipher = new Security.Aes128(xtsKey.Slice(16, 16));

        Span<byte> tweak = stackalloc byte[16];
        tweak.Clear();
        BitConverter.TryWriteBytes(tweak, sectorNumber);

        dataCipher.DecryptXts(data, tweak, tweakCipher);
    }

